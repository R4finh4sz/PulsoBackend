CREATE TABLE guardian_confirmations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    registration_id BIGINT NOT NULL UNIQUE REFERENCES registration_requests(id),
    guardian_name VARCHAR(100) NOT NULL,
    guardian_email VARCHAR(254) NOT NULL,
    status VARCHAR(40) NOT NULL CHECK (status IN ('AWAITING_SCHOOL_CHECK', 'CORRECTION_REQUESTED',
        'AWAITING_GUARDIAN', 'EXPIRED', 'DECLINED', 'UNDER_REVIEW', 'CONFIRMED')),
    correction_reason VARCHAR(2000),
    correction_count INT NOT NULL DEFAULT 0,
    correction_token_hash VARCHAR(128),
    correction_token_expires_at TIMESTAMP WITH TIME ZONE,
    checked_by_id BIGINT REFERENCES school_users(id),
    checked_at TIMESTAMP WITH TIME ZONE,
    check_method VARCHAR(200),
    check_justification VARCHAR(2000),
    resend_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_guardian_confirmation_status ON guardian_confirmations(status, created_at, id);
CREATE UNIQUE INDEX idx_guardian_correction_token ON guardian_confirmations(correction_token_hash);

CREATE TABLE guardian_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    confirmation_id BIGINT NOT NULL REFERENCES guardian_confirmations(id),
    token_hash VARCHAR(128) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at TIMESTAMP WITH TIME ZONE,
    decision VARCHAR(30) CHECK (decision IN ('CONFIRM', 'DECLINE', 'NOT_RECOGNIZED')),
    relationship VARCHAR(30) CHECK (relationship IN ('MOTHER', 'FATHER', 'LEGAL_GUARDIAN', 'OTHER_LEGAL')),
    terms_version BIGINT,
    superseded_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_guardian_invitation_confirmation ON guardian_invitations(confirmation_id, id);
