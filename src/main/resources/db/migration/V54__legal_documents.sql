-- Versioned legal documents published by the admin: privacy policy, guardian term and school data agreement.
-- (The platform terms of use keep their own tables.) Every version is kept; the current one is the highest.
CREATE TABLE legal_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(40) NOT NULL CHECK (type IN ('PRIVACY_POLICY', 'GUARDIAN_TERM', 'SCHOOL_DATA_AGREEMENT',
        'STUDENT_TERM')),
    version INT NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_by_id BIGINT REFERENCES school_users(id) ON DELETE SET NULL,
    CONSTRAINT uq_legal_document_version UNIQUE (type, version)
);
