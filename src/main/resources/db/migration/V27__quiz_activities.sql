CREATE TABLE quiz_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    created_by_id BIGINT NOT NULL REFERENCES school_users(id),
    title VARCHAR(200) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_quiz_activities_subject ON quiz_activities(subject_id);
CREATE TABLE quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL REFERENCES quiz_activities(id),
    question_order INTEGER,
    text VARCHAR(2000) NOT NULL,
    correct_option INTEGER NOT NULL CHECK (correct_option >= 0 AND correct_option < 6)
);
CREATE INDEX idx_quiz_questions_activity ON quiz_questions(activity_id);
CREATE TABLE quiz_options (
    question_id BIGINT NOT NULL REFERENCES quiz_questions(id),
    option_order INTEGER NOT NULL,
    text VARCHAR(500) NOT NULL,
    PRIMARY KEY(question_id, option_order)
);
CREATE TABLE quiz_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL REFERENCES quiz_activities(id),
    student_id BIGINT NOT NULL REFERENCES school_users(id),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    graded_at TIMESTAMP WITH TIME ZONE,
    graded_by_id BIGINT REFERENCES school_users(id),
    correct_answers INTEGER CHECK (correct_answers >= 0),
    score NUMERIC(5,2) CHECK (score >= 0 AND score <= 100),
    UNIQUE(activity_id, student_id),
    CHECK ((graded_at IS NULL AND graded_by_id IS NULL AND correct_answers IS NULL AND score IS NULL)
        OR (graded_at IS NOT NULL AND graded_by_id IS NOT NULL AND correct_answers IS NOT NULL AND score IS NOT NULL))
);
CREATE INDEX idx_quiz_submissions_student ON quiz_submissions(student_id);
CREATE TABLE quiz_answers (
    submission_id BIGINT NOT NULL REFERENCES quiz_submissions(id),
    question_order INTEGER NOT NULL,
    selected_option INTEGER NOT NULL CHECK (selected_option >= 0 AND selected_option < 6),
    PRIMARY KEY(submission_id, question_order)
);
