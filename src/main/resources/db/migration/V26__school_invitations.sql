CREATE TABLE school_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id),
    recipient_id BIGINT NOT NULL REFERENCES school_users(id),
    invited_by_id BIGINT NOT NULL REFERENCES school_users(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    responded_at TIMESTAMP WITH TIME ZONE,
    notification_id BIGINT NOT NULL UNIQUE REFERENCES user_notifications(id),
    UNIQUE (school_id, recipient_id)
);
CREATE INDEX idx_school_invitations_recipient ON school_invitations(recipient_id, created_at);
