CREATE TABLE faqs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    target_role VARCHAR(40) NOT NULL CHECK (target_role IN ('PEDAGOGICAL_COORDINATOR', 'TEACHER', 'STUDENT')),
    message VARCHAR(5000) NOT NULL
);

CREATE INDEX idx_faqs_target_role ON faqs(target_role, id);
