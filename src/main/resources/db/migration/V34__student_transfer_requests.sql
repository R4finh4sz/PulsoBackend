CREATE TABLE student_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES school_users(id),
    origin_id BIGINT NOT NULL REFERENCES schools(id),
    destination_id BIGINT NOT NULL REFERENCES schools(id),
    requested_by_id BIGINT NOT NULL REFERENCES school_users(id),
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(255) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reviewed_by_id BIGINT REFERENCES school_users(id),
    reviewed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_transfer_student_status ON student_transfers(student_id, status);
CREATE INDEX idx_transfer_destination_status ON student_transfers(destination_id, status, requested_at, id);
