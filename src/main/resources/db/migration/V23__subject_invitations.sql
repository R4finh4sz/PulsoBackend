CREATE TABLE subject_teachers (
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    teacher_id BIGINT NOT NULL REFERENCES school_users(id),
    PRIMARY KEY (subject_id, teacher_id)
);
CREATE INDEX idx_subject_teachers_teacher ON subject_teachers(teacher_id);

CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES school_users(id),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_notifications_recipient ON user_notifications(recipient_id, created_at);

CREATE TABLE subject_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    recipient_id BIGINT NOT NULL REFERENCES school_users(id),
    inviter_id BIGINT NOT NULL REFERENCES school_users(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    responded_at TIMESTAMP WITH TIME ZONE,
    notification_id BIGINT NOT NULL UNIQUE REFERENCES user_notifications(id),
    UNIQUE (subject_id, recipient_id)
);
CREATE INDEX idx_subject_invitations_recipient ON subject_invitations(recipient_id, created_at);
