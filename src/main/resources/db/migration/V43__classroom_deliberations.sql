ALTER TABLE classrooms ADD COLUMN graduated_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE classroom_deliberations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT NOT NULL REFERENCES classrooms(id),
    school_id BIGINT NOT NULL REFERENCES schools(id),
    action VARCHAR(20) NOT NULL CHECK (action IN ('TRANSFER', 'GRADUATE')),
    performed_by_id BIGINT NOT NULL REFERENCES school_users(id),
    performed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_deliberation_classroom ON classroom_deliberations(classroom_id, performed_at);

CREATE TABLE classroom_deliberation_students (
    deliberation_id BIGINT NOT NULL REFERENCES classroom_deliberations(id),
    student_id BIGINT NOT NULL REFERENCES school_users(id),
    result VARCHAR(20) NOT NULL CHECK (result IN ('APPROVED', 'FAILED')),
    destination_classroom_id BIGINT REFERENCES classrooms(id),
    PRIMARY KEY (deliberation_id, student_id)
);
CREATE INDEX idx_deliberation_student ON classroom_deliberation_students(student_id);
