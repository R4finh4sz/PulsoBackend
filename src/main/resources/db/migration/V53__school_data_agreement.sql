-- Proof that a school (data controller) accepted the data processing agreement with Pulso (operator).
CREATE TABLE school_data_agreements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id),
    accepted_by_id BIGINT NOT NULL REFERENCES school_users(id),
    version INT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    accepted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ip_address VARCHAR(45),
    CONSTRAINT uq_school_data_agreement UNIQUE (school_id, version)
);
